"""Safe process interruption and exact local optimizer checkpoint restoration."""
import os,random,signal
from pathlib import Path
import numpy as np
import torch
STOP_REQUESTED=False

def install_handlers():
 def stop(signum,frame):
  global STOP_REQUESTED
  STOP_REQUESTED=True
 for sig in [signal.SIGINT,signal.SIGTERM]:signal.signal(sig,stop)

def stopped():return STOP_REQUESTED

def rng_state():
 return dict(python=random.getstate(),numpy=np.random.get_state(),torch=torch.get_rng_state(),cuda=torch.cuda.get_rng_state_all() if torch.cuda.is_initialized() else [])
def restore_rng(state):
 random.setstate(state['python']);np.random.set_state(state['numpy']);torch.set_rng_state(state['torch'])
 if state['cuda']:torch.cuda.set_rng_state_all(state['cuda'])
def atomic_torch_save(path,state):
 path=Path(path);tmp=path.with_suffix('.tmp');torch.save(state,tmp);os.replace(tmp,path)
def load_checkpoint(path):
 # Checkpoints are locally generated by this pipeline and contain optimizer/RNG state.
 return torch.load(path,map_location='cpu',weights_only=False)

def inherited_fds():return tuple(int(x) for x in os.environ.get('PRIVACY_LOCK_FDS','').split(',') if x)
